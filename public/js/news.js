const DAY = 86400000;
const MONTHS = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];
const dayStart = (ms) => { const d = new Date(ms); d.setHours(0, 0, 0, 0); return d.getTime(); };
const dayOf = (iso) => new Date(`${iso}T00:00:00`).getTime();

/** Дни за последнюю неделю (сегодня и шесть дней назад), новые сверху. */
export function recentNews(now = Date.now(), days = 7) {
  const today = dayStart(now);
  return NEWS.filter((d) => {
    const ago = Math.round((today - dayOf(d.date)) / DAY);
    return ago >= 0 && ago < days;
  }).sort((a, b) => (a.date < b.date ? 1 : -1));
}

const dayTitle = (iso) => { const d = new Date(`${iso}T00:00:00`); return `${d.getDate()} ${MONTHS[d.getMonth()]}`; };

/** Блок «Что нового за неделю»: последний день раскрыт, остальные свернуты; нечего показать: пусто. */
export function newsHTML(days) {
  if (!days.length) return '';
  return `<section class="news" aria-label="Что нового за неделю"><h2>Что нового за неделю</h2>${days.map((d, i) => `<details class="nday"${i ? '' : ' open'}><summary>${dayTitle(d.date)}</summary><ul>${d.items.map((s) => `<li>${s}</li>`).join('')}</ul></details>`).join('')}</section>`;
}
